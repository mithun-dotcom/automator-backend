// [{ type: 'h2' | 'h3' | 'li' | 'p', text }]
function blocks() {
  return TEXT.split('\n').map((l) => l.trim()).filter(Boolean).map((line) => {
    if (/^\d+\.\d+\s/.test(line)) return { type: 'h3', text: line };
    if (/^\d+\.\s/.test(line)) return { type: 'h2', text: line };
    if (line.startsWith('* ')) return { type: 'li', text: line.slice(2) };
    return { type: 'p', text: line };
  });
}

module.exports = { TITLE, VERSION, blocks };
